"""Entity hygiene: push-only entities and non-deprecated device lookup."""

import logging

from homeassistant.helpers import entity_registry as er
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.petsafe_freshfeed.const import DOMAIN
from test_owned_hub import make_entry, owned_data


async def _setup(hass, owned):
    owned.device.dps.pop('140', None)
    entry = make_entry(owned, owned_data())
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()
    return entry


async def test_estimate_labels_keep_registry_identity(hass, owned):
    entry = make_entry(owned, owned_data())
    registry = er.async_get(hass)
    # Registry rows represent IDs generated by the pre-upgrade labels.
    old_ids = {
        "meals_left": "sensor.petsafe_freshfeed_meals_left",
        "food_level": "sensor.petsafe_freshfeed_food_level",
        "firmware_a": "sensor.petsafe_freshfeed_firmware_a",
        "firmware_b": "sensor.petsafe_freshfeed_firmware_b",
        "out_of_food": "binary_sensor.petsafe_freshfeed_out_of_food",
        "quick_feed": "sensor.petsafe_freshfeed_quick_feed",
    }
    before = {}
    for key, entity_id in old_ids.items():
        domain, object_id = entity_id.split(".")
        unique_id = f"{entry.entry_id}_{key}"
        row = registry.async_get_or_create(
            domain, DOMAIN, unique_id, config_entry=entry,
            suggested_object_id=object_id,
        )
        assert row.entity_id == entity_id
        before[unique_id] = entity_id
    meals_id = old_ids["meals_left"]
    registry.async_update_entity(meals_id, name="My custom estimate")
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()
    assert await hass.config_entries.async_reload(entry.entry_id)
    await hass.async_block_till_done()
    rows = er.async_entries_for_config_entry(registry, entry.entry_id)
    after = {row.unique_id: row.entity_id for row in rows}
    assert before.items() <= after.items()
    assert registry.async_get(meals_id).name == "My custom estimate"
    names = {"meals_left": "Estimated meals remaining", "food_level": "Estimated food level",
             "firmware_a": "Firmware version", "firmware_b": "Hardware version",
             "out_of_food": "Estimated empty tray", "quick_feed": "Quick feed"}
    entities = [e for platform in hass.data["entity_components"].values()
                for e in platform.entities if getattr(e, "hub", None) is entry.runtime_data]
    for key, name in names.items():
        entity = next(e for e in entities if e.key == key)
        assert entity.name == name
    assert next(e for e in entities if e.key == "quick_feed").options == [
        "idle", "pending", "feeding", "ready", "failed"]


async def test_entities_do_not_poll(hass, owned):
    entry = await _setup(hass, owned)
    hub = entry.runtime_data
    platform_entities = [
        e
        for platform in hass.data["entity_components"].values()
        for e in platform.entities
        if getattr(e, "hub", None) is hub
    ]
    assert len(platform_entities) == 28
    assert all(e.should_poll is False for e in platform_entities)


async def test_no_deprecated_device_lookup(hass, owned, caplog):
    caplog.set_level(logging.WARNING)
    entry = await _setup(hass, owned)
    assert "async_get_device" not in caplog.text
    registry = er.async_get(hass)
    raw_device = entry.runtime_data.device_id
    ours = [e for e in er.async_entries_for_config_entry(registry, entry.entry_id)]
    assert len(ours) == 28
    assert {e.device_id for e in ours} == {raw_device}
    status = next(e for e in ours if e.unique_id == f'{entry.entry_id}_write_status')
    state = hass.states.get(status.entity_id)
    assert state.state == 'blocked'
    assert state.attributes['can_feed'] is False
    assert state.attributes['recovery_phase'] == 'idle'
    quick = next(e for e in ours if e.unique_id == f'{entry.entry_id}_quick_feed')
    assert hass.states.get(quick.entity_id).attributes['command'] is None
